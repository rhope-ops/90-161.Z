      $now = 'Running now. Started ' + (Get-Date -Format 'HH:mm') + '.'
      if ($name -eq 'Clean-up' -and $script:off -eq 1) { & $stepSay 0 $now }
      else { foreach ($kk in @($script:listIndex.Keys)) { if ($steps[$kk].Name -eq $name) { & $stepSay $script:listIndex[$kk] $now } } }
