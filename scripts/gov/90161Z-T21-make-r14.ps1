<#
.SYNOPSIS
  Make, step m3: the 4 text columns of the probe list (internal name = display name). Adds an ITEM line.
.PARAMETER List
  The probe list (from Find-ByFolder).
.PARAMETER Made
  The counts of what was made (columns is raised here).
.PARAMETER Skip
  The counts of what was there already (columns is raised here).
#>
function Add-ProbeColumn($List, [hashtable]$Made, [hashtable]$Skip) {
  $want = @(@{ Name = 'ProbeTest'; Type = 'Text' }, @{ Name = 'ProbeWay'; Type = 'Text' }, @{ Name = 'ProbeResult'; Type = 'Text' },
    @{ Name = 'ProbeDetail'; Type = 'Note' })
  $have = @(Get-RestValue ("_api/web/lists(guid'" + $List.Id + "')/fields?" + '$select=InternalName&$top=2000') | ForEach-Object { [string]$_.InternalName })
  $bad = 0
  foreach ($c in $want) {
    if ($have -contains $c.Name) { $Skip.columns++; continue }
    $extra = $(if ($c.Type -eq 'Note') { ' RichText="FALSE" NumLines="6"' } else { '' })
    $xml = '<Field Name="' + $c.Name + '" StaticName="' + $c.Name + '" DisplayName="' + $c.Name + '" Required="FALSE" Type="' + $c.Type + '"' + $extra + '></Field>'
    $body = @{ parameters = @{ __metadata = @{ type = 'SP.XmlSchemaFieldCreationInformation' }; SchemaXml = $xml; Options = 24 } } | ConvertTo-Json -Depth 20 -Compress
    try { $null = Invoke-Rest 'Post' ("_api/web/lists(guid'" + $List.Id + "')/fields/createfieldasxml") $body; $Made.columns++ } catch { $bad++ }
  }
  Add-Item 'm3-columns' $(if ($bad -eq 0) { 'PASS' } else { 'FAIL' }) ('columns made=' + $Made.columns + ' already there=' + $Skip.columns + ' refused=' + $bad)
}

<#
.SYNOPSIS
  Make, step m4: the list's own permissions: the site's copied, then Contribute for the associated Visitors group on this
  list only. Adds an ITEM line (and a NOTE when the site has no Visitors group).
.PARAMETER Made
  The counts of what was made (permissions is raised for each change).
#>
function Grant-ProbePermission([hashtable]$Made) {
  $lst = Find-ByFolder $ListFolder
  $lbase = "_api/web/lists(guid'" + $lst.Id + "')"
  if (-not $lst.HasUniqueRoleAssignments) {
    $null = Invoke-Rest 'Post' ($lbase + '/breakroleinheritance(copyRoleAssignments=true,clearSubscopes=true)') '{}'
    $Made.permissions++
  }
  $visitorId = Get-VisitorGroupId
  if ($visitorId -le 0) {
    $script:lines.Add('NOTE m4: no associated Visitors group on this site, so Contribute was not added; the T4 test needs a Visitors group')
    Add-Item 'm4-permissions' 'PASS' ('own permissions on the list (copied now=' + $Made.permissions + '); Visitors group not found')
    return
  }
  $contribute = 0
  try { $contribute = [int](Get-RestValue '_api/web/roledefinitions?$filter=RoleTypeKind%20eq%203&$select=Id')[0].Id } catch { $contribute = 0 }
  if ($contribute -le 0) { throw 'ROLE Contribute not found on the site.' }
  $has = $false
  $bindings = $lbase + '/roleassignments/getbyprincipalid(' + $visitorId + ')/roledefinitionbindings?$select=Id'
  try { $has = @(Get-RestValue $bindings | Where-Object { [int]$_.Id -eq $contribute }).Count -gt 0 } catch { $has = $false }
  if (-not $has) {
    $null = Invoke-Rest 'Post' ($lbase + '/roleassignments/addroleassignment(principalid=' + $visitorId + ',roledefid=' + $contribute + ')') '{}'
    $Made.permissions++
  }
  Add-Item 'm4-permissions' 'PASS' ('own permissions on the list, Visitors group has Contribute (changes now=' + $Made.permissions + ')')
}

<#
.SYNOPSIS
  Make, step m5: saves the fake workbook from the text block in this module (the repo holds no .xlsx: the personal-data
  scan cannot read a binary file), then uploads it. No macro workbook (PFM 17 Nov 26: endpoint security risk).
.PARAMETER Library
  The probe library (from Find-ByFolder).
.PARAMETER Made
  The counts of what was made (files is raised for an upload).
.PARAMETER Skip
  The counts of what was there already (files is raised when the workbook is in the library).
#>
function Send-FakeWorkbook($Library, [hashtable]$Made, [hashtable]$Skip) {
  $wrote = 0
  foreach ($w in @(, @($BookName, $FakeBookBase64))) {
    $bytes = [Convert]::FromBase64String((([string]$w[1] -split '\s+') -join ''))
    $path = Join-Path $script:dir $w[0]
    $same = $false
    if (Test-Path -LiteralPath $path -PathType Leaf) {
      $cur = [IO.File]::ReadAllBytes($path)
      $same = ($cur.Length -eq $bytes.Length) -and ([Convert]::ToBase64String($cur) -eq [Convert]::ToBase64String($bytes))
    }
    if (-not $same) { [IO.File]::WriteAllBytes($path, $bytes); $wrote++ }
  }
  $script:lines.Add('ITEM m5a-workbooks INFO fake workbook saved to the T21 folder now=' + $wrote)
  $filesUri = "_api/web/lists(guid'" + $Library.Id + "')/rootfolder/files?" + '$select=Name&$top=500'
  $inLib = @(Get-RestValue $filesUri | ForEach-Object { [string]$_.Name })
  foreach ($n in @($BookName)) {
    if ($inLib -contains $n) { $Skip.files++; continue }
    $null = Add-PnPFile -Path (Join-Path $script:dir $n) -Folder $LibFolder -ErrorAction Stop
    $Made.files++
  }
  $inLib = @(Get-RestValue $filesUri | ForEach-Object { [string]$_.Name })
  $ok = ($inLib -contains $BookName)
  Add-Item 'm5-files' $(if ($ok) { 'PASS' } else { 'FAIL' }) ('files in the library: the workbook there=' + $(if ($ok) { 'yes' } else { 'no' }) + ' (uploaded now=' + $Made.files + ')')
}

<#
.SYNOPSIS
  The part Make: the library and the list (m1, m2; the same cmdlet T16 uses for its library), the columns, the
  permissions, the workbook and the test page (m3 to m6), then the MADE and SKIPPED count lines. A second run changes
  nothing on the site.
#>
function Invoke-MakePart {
  $made = @{ library = 0; list = 0; columns = 0; permissions = 0; files = 0 }
  $skip = @{ library = 0; list = 0; columns = 0; permissions = 0; files = 0 }
  Write-Now 'Looking for the library and the list'
  $lib = Find-ByFolder $LibFolder
  if ($lib) { $skip.library++ } else {
    Write-Now ('Making the library ' + $LibTitle)
    $null = New-PnPList -Title $LibTitle -Template DocumentLibrary -Url $LibFolder -ErrorAction Stop
    $made.library++; $lib = Find-ByFolder $LibFolder
  }
  Add-Item 'm1-library' $(if ($lib) { 'PASS' } else { 'FAIL' }) $(if ($lib) { 'library there (made=' + $made.library + ')' } else { 'library not on the site after the create step' })
  $lst = Find-ByFolder $ListFolder
  if ($lst) { $skip.list++ } else {
    Write-Now ('Making the list ' + $ListTitle)
    $null = New-PnPList -Title $ListTitle -Template GenericList -Url ('Lists/' + $ListFolder) -ErrorAction Stop
    $made.list++; $lst = Find-ByFolder $ListFolder
  }
  Add-Item 'm2-list' $(if ($lst) { 'PASS' } else { 'FAIL' }) $(if ($lst) { 'list there (made=' + $made.list + ')' } else { 'list not on the site after the create step' })
  if (-not $lib -or -not $lst) { throw 'LIST or library missing after the create step; nothing more was done.' }
  Write-Now 'Adding the 4 columns of the list'
  Add-ProbeColumn $lst $made $skip
  Write-Now 'Setting the permissions of the list'
  Grant-ProbePermission $made
  Write-Now 'Saving and uploading the fake workbook'
  Send-FakeWorkbook $lib $made $skip
  # m6: the test page (it holds the site address: it stays in the T21 folder).
  $n = Write-LinksPage $script:dir $script:site
  Add-Item 'm6-page' 'PASS' ('test page in the T21 folder, links=' + $n)
  $script:lines.Add('MADE library=' + $made.library + ' list=' + $made.list + ' columns=' + $made.columns + ' permission changes=' + $made.permissions + ' files=' + $made.files)
  $script:lines.Add('SKIPPED (already there) library=' + $skip.library + ' list=' + $skip.list + ' columns=' + $skip.columns + ' files=' + $skip.files)
}

# The part Open (no sign-in): writes the test page again and opens it in the browser.
function Invoke-OpenPart {
  Write-Now 'Writing the test page'
  $n = Write-LinksPage $script:dir $script:site
  Add-Item 'o1-page' 'PASS' ('test page written, links=' + $n)
  if (-not $NoLaunch) { Write-Now 'Opening the test page in the browser'; Start-Process -FilePath (Join-Path $script:dir $LinksName) }
  Add-Item 'o2-open' 'PASS' ('test page opened in the browser=' + $(if ($NoLaunch) { 'no (test run)' } else { 'yes' }))
}
