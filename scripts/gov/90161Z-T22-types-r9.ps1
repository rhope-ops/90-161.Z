'// R7 (R32 W2): the mouse wheel scrolls what is under the pointer, whatever control has the focus.',
'public class Wheel : IMessageFilter {',
'public const int WM_MOUSEWHEEL = 0x020A;',
'public Form Owner = null;',
'public Control Stop = null;',
'// The message filter: a wheel message for a control of Owner goes to Route; true = handled here. The pointer comes',
'// in screen pixels; it is turned into the client pixels of Owner once, and the rest is the managed control tree.',
'public bool PreFilterMessage(ref Message m) {',
'if (m.Msg != WM_MOUSEWHEEL || Owner == null || Owner.IsDisposed || !Owner.IsHandleCreated) { return false; }',
'Control from = Control.FromChildHandle(m.HWnd);',
'if (from == null || from.FindForm() != Owner) { return false; }',
'long lp = m.LParam.ToInt64();',
'Point pt = new Point((short)(lp & 0xFFFF), (short)((lp >> 16) & 0xFFFF));',
'int delta = (short)((m.WParam.ToInt64() >> 16) & 0xFFFF);',
'return Route(Owner, Stop, Owner.PointToClient(pt), delta) != null;',
'}',
'// A wheel message as Windows sends it: the pointer in screen pixels, delta 120 per notch (positive = away from you).',
'public static Message Make(IntPtr hwnd, Point screen, int delta) {',
'uint wp = ((uint)(delta & 0xFFFF)) << 16;',
'uint lp = (((uint)(screen.Y & 0xFFFF)) << 16) | ((uint)(screen.X & 0xFFFF));',
'return Message.Create(hwnd, WM_MOUSEWHEEL, new IntPtr(unchecked((int)wp)), new IntPtr(unchecked((int)lp)));',
'}',
'// The client origin of c in the client pixels of root: the sum of the Locations up the parents (a child Location is',
'// in its parent client pixels, scroll included; the containers here have no border).',
'public static Point ClientOf(Control c, Control root) {',
'int x = 0, y = 0;',
'for (Control k = c; k != null && k != root; k = k.Parent) { x += k.Left; y += k.Top; }',
'return new Point(x, y);',
'}',
'// The deepest visible control of root under a point in root client pixels, from the control tree (front child first,',
'// as Windows hit-tests): a point outside a control client area (its scroll bar) stops at that control.',
'public static Control Under(Control root, Point client) {',
'Control c = root;',
'Point p = client;',
'while (true) {',
'if (!c.ClientRectangle.Contains(p)) { return c; }',
'Control hit = null;',
'foreach (Control k in c.Controls) { if (k.Visible && k.Bounds.Contains(p)) { hit = k; break; } }',
'if (hit == null) { return c; }',
'p = new Point(p.X - hit.Left, p.Y - hit.Top);',
'c = hit;',
'}',
'}',
'// Routes one wheel turn at a point in root client pixels: the control it scrolls (it is scrolled), or null when the',
'// pointer is not on the window, is on a list or a text box with its own scroll bar, or nothing under it can scroll.',
'public static Control Route(Control root, Control stop, Point client, int delta) {',
'if (delta == 0 || !root.ClientRectangle.Contains(client)) { return null; }',
'Control under = Under(root, client);',
'if (under is ComboBox) { return null; }',
'TextBoxBase tb = under as TextBoxBase;',
'if (tb != null && tb.Multiline && tb.TabStop) { return null; }',
'Control t = Target(under, stop, delta);',
'if (t != null) { Apply(t, delta); }',
'return t;',
'}',
'// The first control from under up to stop that can still scroll that way: a grid with rows out of view, or a',
'// panel that scrolls (AutoScroll with its vertical bar showing).',
'public static Control Target(Control under, Control stop, int delta) {',
'for (Control c = under; c != null; c = c.Parent) {',
'DataGridView g = c as DataGridView;',
'if (g != null && GridCan(g, delta)) { return g; }',
'ScrollableControl s = c as ScrollableControl;',
'if (s != null && s.AutoScroll && s.VerticalScroll.Visible && PanelCan(s, delta)) { return s; }',
'if (c == stop) { break; }',
'}',
'return null;',
'}',
'// True when grid g can scroll up (delta > 0) or down.',
'public static bool GridCan(DataGridView g, int delta) {',
'if (g.RowCount == 0 || g.FirstDisplayedScrollingRowIndex < 0) { return false; }',
'if (delta > 0) { return g.FirstDisplayedScrollingRowIndex > 0; }',
'return g.FirstDisplayedScrollingRowIndex + g.DisplayedRowCount(false) < g.RowCount;',
'}',
'// True when panel s can scroll up (delta > 0) or down.',
'public static bool PanelCan(ScrollableControl s, int delta) {',
'int y = -s.AutoScrollPosition.Y;',
'if (delta > 0) { return y > 0; }',
'return y < s.DisplayRectangle.Height - s.ClientSize.Height;',
'}',
'// Scrolls t: a grid by the Windows wheel lines per notch (rows), a panel by delta pixels, as a panel does by itself.',
'public static void Apply(Control t, int delta) {',
'DataGridView g = t as DataGridView;',
'if (g != null) {',
'int lines = SystemInformation.MouseWheelScrollLines;',
'if (lines <= 0) { lines = Math.Max(1, g.DisplayedRowCount(false)); }',
'int rows = (int)Math.Round(-delta / 120.0 * lines);',
'if (rows == 0) { rows = delta > 0 ? -1 : 1; }',
'g.FirstDisplayedScrollingRowIndex = Math.Max(0, Math.Min(g.RowCount - 1, g.FirstDisplayedScrollingRowIndex + rows));',
'return;',
'}',
'ScrollableControl s = (ScrollableControl)t;',
's.AutoScrollPosition = new Point(-s.AutoScrollPosition.X, -s.AutoScrollPosition.Y - delta);',
'}',
'}',
'// R8 (R35 W7, R34 finding 7): the logo in 2 colors for Windows high contrast, and the counts that prove it. Each',
'// reads the pixels of the bitmap it is given (no copy, so no cover is rounded).',
'public static class Logo {',
'// A copy of src in 2 colors: each pixel keeps its cover (alpha); a dark pixel takes dark, a light one light.',
'// Light: a weighted brightness of 128 or more (of 255): the white rings and page and the yellow arc; dark: the blue disc and Z.',
'public static Bitmap TwoTone(Bitmap src, Color dark, Color light) {',
'Bitmap o = new Bitmap(src.Width, src.Height, System.Drawing.Imaging.PixelFormat.Format32bppArgb);',
'for (int y = 0; y < src.Height; y++) {',
'for (int x = 0; x < src.Width; x++) {',
'Color c = src.GetPixel(x, y);',
'if (c.A == 0) { continue; }',
'Color t = (c.R * 299 + c.G * 587 + c.B * 114) >= 128000 ? light : dark;',
'o.SetPixel(x, y, Color.FromArgb(c.A, t.R, t.G, t.B));',
'}',
'}',
'return o;',
'}',
'// The number of pixels of b with any cover whose color (cover left out) is neither p nor q.',
'public static int Other(Bitmap b, Color p, Color q) {',
'int n = 0;',
'for (int y = 0; y < b.Height; y++) {',
'for (int x = 0; x < b.Width; x++) {',
'Color c = b.GetPixel(x, y);',
'if (c.A == 0) { continue; }',
'if (!Same(c, p) && !Same(c, q)) { n++; }',
'}',
'}',
'return n;',
'}',
'// The number of pixels whose color or cover differs between a and b; -1 when their sizes differ.',
'public static int Diff(Bitmap a, Bitmap b) {',
'if (a.Width != b.Width || a.Height != b.Height) { return -1; }',
'int n = 0;',
'for (int j = 0; j < a.Height; j++) {',
'for (int i = 0; i < a.Width; i++) {',
'Color c = a.GetPixel(i, j);',
'Color d = b.GetPixel(i, j);',
'if (c.A != d.A || (c.A != 0 && !Same(c, d))) { n++; }',
'}',
'}',
'return n;',
'}',
'static bool Same(Color a, Color b) { return a.R == b.R && a.G == b.G && a.B == b.B; }',
'}',
'}'
