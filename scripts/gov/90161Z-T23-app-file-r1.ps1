  $who = Get-TaskId $Id
  $dir = Get-TaskDir $who.Id $task 'T23' -Create
  $path = Join-Path $dir '90161Z-T23-app-file-r1.msapp'
  if (Test-Path -LiteralPath $path) { Remove-Item -LiteralPath $path -Force }
  Add-Type -AssemblyName System.IO.Compression
  Add-Type -AssemblyName System.IO.Compression.FileSystem
  $sha = [System.Security.Cryptography.SHA256]::Create()
  $bad = 0
  $fs = [System.IO.File]::Open($path, [System.IO.FileMode]::CreateNew)
  try {
    $zip = New-Object System.IO.Compression.ZipArchive($fs, [System.IO.Compression.ZipArchiveMode]::Create)
    try {
      foreach ($p in $parts) {
        $bytes = [System.Text.Encoding]::ASCII.GetBytes([string]$p.Text)
        $hash = -join ($sha.ComputeHash($bytes) | ForEach-Object { $_.ToString('x2') })
        if ($hash -ne $p.Sha) { $bad++; Write-Output ('ITEM app-part FAIL ' + $p.Name + ': the bytes differ from the build') }
        $entry = $zip.CreateEntry($p.Name, [System.IO.Compression.CompressionLevel]::Optimal)
        $es = $entry.Open()
        try { $es.Write($bytes, 0, $bytes.Length) } finally { $es.Dispose() }
      }
    } finally { $zip.Dispose() }
  } finally { $fs.Dispose() }
  $size = (Get-Item -LiteralPath $path).Length
  if ($bad -gt 0) { throw ('' + $bad + ' of ' + $parts.Count + ' parts differ from the build') }
  try { Set-Clipboard -Value $path; $clip = 'the file path is on the clipboard' } catch { $clip = 'the clipboard could not be set' }
  Write-Output ('ITEM app-file PASS made 90161Z-T23-app-file-r1.msapp in T23: bytes=' + $size + ', parts=' + $parts.Count + ' (each SHA-256 matches the build); ' + $clip)
  Write-Output 'PASS T23 app file r1: 1 of 1'
