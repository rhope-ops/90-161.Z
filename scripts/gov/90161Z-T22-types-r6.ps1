<#
.SYNOPSIS
  90-161.Z Task 22 r5, part "types": the C# source of the window's own drawn controls, as text.
.DESCRIPTION
  Pfm.Gfx (rounded shapes), Pfm.Chip (a rounded status chip), Pfm.Card (a card with a thin edge and an optional top
  bar), Pfm.Steps (the 12 step dots), Pfm.RailItem (a rail button), Pfm.LinkText (R30 V2: the link of a crumb, drawn
  in the crumb's own font with no padding, so the crumb reads as one line) and Rade.Native (HideCaret, used by the
  RADE shared UI file). The end of this file compiles the text with Add-Type, once per process; the main script loads
  this file after Windows Forms and System.Drawing.
  Inputs: none. Outputs: the compiled types Pfm.* and Rade.Native (a failed Rade.Native only leaves the caret visible).
  Run: not alone; 90161Z-T22-pfm-window-r5.ps1 dot-sources it from its own folder.
  Network: none.
  Writes: none.
  Credentials: none.
#>
# One C# line per string; the lines are joined with CR LF. A long statement goes on two strings (C# ignores the break).
$PfmCs=(@(
'using System;',
'using System.Drawing;',
'using System.Drawing.Drawing2D;',
'using System.Windows.Forms;',
'namespace Pfm {',
'public static class Gfx {',
'public static GraphicsPath Round(RectangleF r, float rad) {',
'GraphicsPath p = new GraphicsPath();',
'if (rad <= 0.5f) { p.AddRectangle(r); return p; }',
'float d = rad * 2f;',
'p.AddArc(r.X, r.Y, d, d, 180, 90);',
'p.AddArc(r.Right - d, r.Y, d, d, 270, 90);',
'p.AddArc(r.Right - d, r.Bottom - d, d, d, 0, 90);',
'p.AddArc(r.X, r.Bottom - d, d, d, 90, 90);',
'p.CloseFigure();',
'return p;',
'}',
'public static void RoundRegion(Control c, int rad) {',
'if (c.Width < 4 || c.Height < 4) { return; }',
'using (GraphicsPath p = Round(new RectangleF(0, 0, c.Width, c.Height), rad)) {',
'Region old = c.Region;',
'c.Region = new Region(p);',
'if (old != null) { old.Dispose(); }',
'}',
'}',
'}',
'public class Chip : Control {',
'public Color Fill = Color.White;',
'public Chip() {',
'SetStyle(ControlStyles.UserPaint | ControlStyles.AllPaintingInWmPaint | ControlStyles.OptimizedDoubleBuffer | ControlStyles.ResizeRedraw, true);',
'TabStop = false;',
'}',
'protected override void OnPaint(PaintEventArgs e) {',
'Graphics g = e.Graphics;',
'g.Clear(BackColor);',
'g.SmoothingMode = SmoothingMode.AntiAlias;',
'using (GraphicsPath p = Gfx.Round(new RectangleF(0, 0, Width - 1, Height - 1), Height / 2f)) {',
'using (SolidBrush b = new SolidBrush(Fill)) { g.FillPath(b, p); }',
'}',
'TextRenderer.DrawText(g, Text, Font, ClientRectangle, ForeColor,',
'  TextFormatFlags.HorizontalCenter | TextFormatFlags.VerticalCenter | TextFormatFlags.SingleLine | TextFormatFlags.NoPrefix | TextFormatFlags.NoPadding);',
'}',
'}',
'public class Card : FlowLayoutPanel {',
'public Color Line = Color.Gray;',
'public Color TopFill = Color.Transparent;',
'public Color Outer = Color.White;',
'public int TopH = 0;',
'public int Radius = 6;',
'public Card() { DoubleBuffered = true; ResizeRedraw = true; }',
'protected override void OnPaint(PaintEventArgs e) {',
'base.OnPaint(e);',
'Graphics g = e.Graphics;',
'g.SmoothingMode = SmoothingMode.AntiAlias;',
'using (GraphicsPath p = Gfx.Round(new RectangleF(0.5f, 0.5f, Width - 1.5f, Height - 1.5f), Radius)) {',
'using (Region r = new Region(new Rectangle(0, 0, Width, Height))) {',
'r.Exclude(p);',
'using (SolidBrush b = new SolidBrush(Outer)) { g.FillRegion(b, r); }',
'}',
'if (TopH > 0) {',
'GraphicsState st = g.Save();',
'g.SetClip(p);',
'using (SolidBrush b = new SolidBrush(TopFill)) { g.FillRectangle(b, 0, 0, Width, TopH); }',
'g.Restore(st);',
'}',
'using (Pen pen = new Pen(Line, 1f)) { g.DrawPath(pen, p); }',
'}',
'}',
'}',
'public class Steps : Control {',
'public string[] Labels = new string[0];',
'public int Current = 1;',
'public int Dot = 26;',
'public Color DoneFill = Color.Blue, DoneText = Color.White, NowFill = Color.Yellow, NowLine = Color.Navy, NowText = Color.Black;',
'public Color TodoFill = Color.White, TodoLine = Color.Gray, TodoText = Color.Black, ConnDone = Color.Blue, ConnTodo = Color.Gray;',
'public Color LabelDone = Color.Black, LabelNow = Color.Navy, LabelTodo = Color.Gray;',
'public Font[] Fonts = new Font[0];',
'public Font[] FontsB = new Font[0];',
'public Steps() {',
'SetStyle(ControlStyles.UserPaint | ControlStyles.AllPaintingInWmPaint | ControlStyles.OptimizedDoubleBuffer | ControlStyles.ResizeRedraw, true);',
'TabStop = false;',
'}',
'protected override void OnPaint(PaintEventArgs e) {',
'Graphics g = e.Graphics;',
'g.Clear(BackColor);',
'int n = Labels.Length;',
'if (n == 0 || Fonts.Length == 0) { return; }',
'g.SmoothingMode = SmoothingMode.AntiAlias;',
'float cell = (float)Width / n;',
'int fi = Fonts.Length - 1;',
'for (int k = 0; k < Fonts.Length; k++) {',
'bool ok = true;',
'for (int i = 0; i < n && ok; i++) {',
'Font f = (i + 1 == Current) ? FontsB[k] : Fonts[k];',
'foreach (string w in Labels[i].Split('' '')) {',
'if (TextRenderer.MeasureText(w, f, new Size(100000, 0), TextFormatFlags.NoPadding | TextFormatFlags.NoPrefix).Width > cell - 4) { ok = false; break; }',
'}',
'}',
'if (ok) { fi = k; break; }',
'}',
'float top = 2f;',
'float cy = top + Dot / 2f;',
'for (int i = 1; i < n; i++) {',
'Color c = (i + 1 <= Current) ? ConnDone : ConnTodo;',
'using (Pen p = new Pen(c, 3f)) { g.DrawLine(p, (i - 0.5f) * cell, cy, (i + 0.5f) * cell, cy); }',
'}',
'for (int i = 0; i < n; i++) {',
'int num = i + 1;',
'float cx = (i + 0.5f) * cell;',
'RectangleF rc = new RectangleF(cx - Dot / 2f, top, Dot, Dot);',
'Color fill; Color line; Color tx; float lw;',
'if (num < Current) { fill = DoneFill; line = DoneFill; tx = DoneText; lw = 2f; }',
'else if (num == Current) { fill = NowFill; line = NowLine; tx = NowText; lw = 3f; }',
'else { fill = TodoFill; line = TodoLine; tx = TodoText; lw = 2f; }',
'using (SolidBrush b = new SolidBrush(fill)) { g.FillEllipse(b, rc); }',
'RectangleF ri = rc;',
'ri.Inflate(-lw / 2f, -lw / 2f);',
'using (Pen p = new Pen(line, lw)) { g.DrawEllipse(p, ri); }',
'TextRenderer.DrawText(g, num.ToString(), FontsB[fi], Rectangle.Round(rc), tx,',
'  TextFormatFlags.HorizontalCenter | TextFormatFlags.VerticalCenter | TextFormatFlags.SingleLine | TextFormatFlags.NoPadding | TextFormatFlags.NoPrefix);',
'Rectangle lr = new Rectangle((int)(i * cell) + 1, (int)(top + Dot + 4), (int)cell - 2, Height - (int)(top + Dot + 4));',
'Color lc = (num < Current) ? LabelDone : ((num == Current) ? LabelNow : LabelTodo);',
'TextRenderer.DrawText(g, Labels[i], (num == Current) ? FontsB[fi] : Fonts[fi], lr, lc,',
'  TextFormatFlags.HorizontalCenter | TextFormatFlags.Top | TextFormatFlags.WordBreak | TextFormatFlags.NoPadding | TextFormatFlags.NoPrefix);',
'}',
'}',
'}',
'public class RailItem : Button {',
'public bool On = false;',
'public string Badge = "";',
'public Color Back = Color.Navy, OnBack = Color.White, Fore = Color.White, OnFore = Color.Navy, HotLine = Color.White;',
'public Color FocusLine = Color.Yellow, FocusOn = Color.Navy, BadgeFill = Color.Yellow, BadgeText = Color.Black;',
'public Font BoldFont = null;',
'private bool hot = false;',
'public RailItem() {',
'SetStyle(ControlStyles.UserPaint | ControlStyles.AllPaintingInWmPaint | ControlStyles.OptimizedDoubleBuffer | ControlStyles.ResizeRedraw, true);',
'FlatStyle = FlatStyle.Flat;',
'TabStop = true;',
'}',
'protected override void OnMouseEnter(EventArgs e) { hot = true; Invalidate(); base.OnMouseEnter(e); }',
'protected override void OnMouseLeave(EventArgs e) { hot = false; Invalidate(); base.OnMouseLeave(e); }',
'protected override void OnGotFocus(EventArgs e) { Invalidate(); base.OnGotFocus(e); }',
'protected override void OnLostFocus(EventArgs e) { Invalidate(); base.OnLostFocus(e); }',
'protected override void OnPaint(PaintEventArgs e) {',
'Graphics g = e.Graphics;',
'g.Clear(Back);',
'g.SmoothingMode = SmoothingMode.AntiAlias;',
'RectangleF rc = new RectangleF(0.5f, 0.5f, Width - 2f, Height - 2f);',
'using (GraphicsPath p = Gfx.Round(rc, 4f)) {',
'if (On) { using (SolidBrush b = new SolidBrush(OnBack)) { g.FillPath(b, p); } }',
'else if (hot) { using (Pen pen = new Pen(HotLine, 1f)) { g.DrawPath(pen, p); } }',
'}',
'if (Focused) {',
'RectangleF f = rc;',
'f.Inflate(-2f, -2f);',
'using (GraphicsPath q = Gfx.Round(f, 3f)) { using (Pen pen = new Pen(On ? FocusOn : FocusLine, 2f)) { g.DrawPath(pen, q); } }',
'}',
'int right = Width - 14;',
'if (Badge.Length > 0) {',
'int d = Height / 2;',
'Rectangle br = new Rectangle(Width - 14 - d, (Height - d) / 2, d, d);',
'using (SolidBrush b = new SolidBrush(BadgeFill)) { g.FillEllipse(b, br); }',
'TextRenderer.DrawText(g, Badge, (BoldFont != null) ? BoldFont : Font, br, BadgeText,',
'  TextFormatFlags.HorizontalCenter | TextFormatFlags.VerticalCenter | TextFormatFlags.SingleLine | TextFormatFlags.NoPadding | TextFormatFlags.NoPrefix);',
'right = br.Left - 6;',
'}',
'Rectangle tr = new Rectangle(14, 0, Math.Max(1, right - 14), Height);',
'TextRenderer.DrawText(g, Text, (On && BoldFont != null) ? BoldFont : Font, tr, On ? OnFore : Fore,',
'  TextFormatFlags.Left | TextFormatFlags.VerticalCenter | TextFormatFlags.SingleLine | TextFormatFlags.NoPrefix | TextFormatFlags.EndEllipsis);',
'}',
'}',
'public class LinkText : Button {',
'private const TextFormatFlags LinkFlags = TextFormatFlags.Left | TextFormatFlags.VerticalCenter | TextFormatFlags.SingleLine |',
'  TextFormatFlags.NoPrefix | TextFormatFlags.NoPadding;',
'public LinkText() {',
'SetStyle(ControlStyles.UserPaint | ControlStyles.AllPaintingInWmPaint | ControlStyles.OptimizedDoubleBuffer | ControlStyles.ResizeRedraw, true);',
'FlatStyle = FlatStyle.Flat;',
'FlatAppearance.BorderSize = 0;',
'TabStop = true;',
'UseMnemonic = false;',
'}',
'public override Size GetPreferredSize(Size proposed) {',
'Size t;',
'using (Graphics g = Graphics.FromHwnd(IntPtr.Zero)) { t = TextRenderer.MeasureText(g, Text, Font, new Size(100000, 0), LinkFlags); }',
'return new Size(t.Width + 1, Math.Max(MinimumSize.Height, t.Height));',
'}',
'protected override void OnPaint(PaintEventArgs e) {',
'e.Graphics.Clear(BackColor);',
'TextRenderer.DrawText(e.Graphics, Text, Font, ClientRectangle, ForeColor, LinkFlags);',
'}',
'}',
'}'
) -join "`r`n")
$NativeCs=(@(
'using System;',
'using System.Runtime.InteropServices;',
'namespace Rade {',
'public static class Native {',
'[DllImport("user32.dll")] public static extern bool HideCaret(IntPtr hWnd);',
'}',
'}'
) -join "`r`n")
# Compiled once per process (a second run in the same PowerShell finds the types).
if (-not ('Pfm.Card' -as [type])) { Add-Type -ReferencedAssemblies 'System.Windows.Forms', 'System.Drawing' -TypeDefinition $PfmCs }
if (-not ('Rade.Native' -as [type])) { try { Add-Type -TypeDefinition $NativeCs } catch { $null = $_ } }
