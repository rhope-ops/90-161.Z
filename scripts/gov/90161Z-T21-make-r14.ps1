# Encodes a text for HTML (the test page).
function Get-HtmlText([string]$Text) { return [System.Net.WebUtility]::HtmlEncode($Text) }

<#
.SYNOPSIS
  Writes the test page: one big link per thing to open. Colors and font as the RADE window.
.DESCRIPTION
  The page holds the site address, so it stays in the T21 folder on this computer; it is never a result file.
.PARAMETER Dir
  The T21 folder.
.PARAMETER Site
  The site address.
.OUTPUTS
  System.Int32. The number of links on the page.
#>
function Write-LinksPage([string]$Dir, [string]$Site) {
  $s = $Site.TrimEnd('/')
  $links = @(
