#!/usr/bin/env python3
"""Build the R27 app file test script scripts/gov/90161Z-T23-app-file-r1.ps1 (DECISIONS 2026-11-16: one tiny cloud-built
app file, uploaded in 2 places in Power Apps).

Source: samples/90161Z-T23-app-file-src-r1/ (one screen, one label; Power Apps source format 0.24).
Step 1: the Power Platform CLI packs the source into a .msapp ("pac canvas pack", preview; version 1.44.2 from NuGet,
newer versions have no "canvas pack"; needs the .NET SDK 8):
    dotnet tool install --tool-path <dir> Microsoft.PowerApps.CLI.Tool --version 1.44.2
    <dir>/pac telemetry disable        (the session proxy refuses its telemetry hosts)
Step 2: this script writes every entry of that .msapp (all ASCII JSON) into the task script as text lines, with its SHA-256.
On the gov device the task script zips the entries back into 90161Z-T23-app-file-r1.msapp and checks each hash, so the
file is byte for byte the entries pac made. The .msapp itself is not in the repo: the personal-data guard cannot scan a
binary file, and its skip list is the PFM's to change.
Run: PAC=<dir>/pac python3 scripts/build_test_app.py. Never hand-edit the output: change the source and run this again.
"""
import hashlib
import os
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'samples/90161Z-T23-app-file-src-r1'
OUT = ROOT / 'scripts/gov/90161Z-T23-app-file-r1.ps1'
APP = '90161Z-T23-app-file-r1.msapp'

HEAD = r'''<#
.SYNOPSIS
  90-161.Z Task 23 app file, r1 (R27; PFM 16 Nov 26). Makes one tiny Power Apps app file for the upload test. No sign-in.
.DESCRIPTION
  Generated by scripts/build_test_app.py from samples/90161Z-T23-app-file-src-r1 (never hand-edit this file).
  What it is for: Microsoft Learn names no supported way to build a Power Apps app outside Power Apps. The round uploads
  one tiny app file, built in the cloud by the Power Platform CLI (pac canvas pack 1.44.2), in 2 places in Power Apps,
  to settle with evidence whether such a file opens. About 1 minute (an estimate).
  It writes one file, T23\90161Z-T23-app-file-r1.msapp (one screen with the text "90-161.Z test app"; fake content only),
  checks the SHA-256 of each of its parts against the build, and puts the file's full path on the clipboard. It changes
  nothing else and opens no network connection.
  Output: lines that start with ITEM and PASS or FAIL.
  Parameters (used by RADE): -Id, -NoPause.
#>
param([string]$Id, [switch]$NoPause)
$task = 'T23'
$ErrorActionPreference = 'Stop'

# >>> task-common: generated from scripts/gov/src/task-common.ps1 by scripts/build_task_scripts.py (do not edit)
# <<< task-common

'''

TAIL = r'''
$code = 0
try {
  $who = Get-TaskId $Id
  $dir = Get-TaskDir $who.Id $task 'T23' -Create
  $path = Join-Path $dir '__APP__'
  if (Test-Path -LiteralPath $path) { Remove-Item -LiteralPath $path -Force }
  Add-Type -AssemblyName System.IO.Compression
  Add-Type -AssemblyName System.IO.Compression.FileSystem
  $sha = [System.Security.Cryptography.SHA256]::Create()
  $bad = 0
  $fs = [System.IO.File]::Open($path, [System.IO.FileMode]::CreateNew)
  try {
    $zip = New-Object System.IO.Compression.ZipArchive($fs, [System.IO.Compression.ZipArchiveMode]::Create)
    try {
      foreach ($p in $parts) {
        $bytes = [System.Text.Encoding]::ASCII.GetBytes([string]$p.Text)
        $hash = -join ($sha.ComputeHash($bytes) | ForEach-Object { $_.ToString('x2') })
        if ($hash -ne $p.Sha) { $bad++; Write-Output ('ITEM app-part FAIL ' + $p.Name + ': the bytes differ from the build') }
        $entry = $zip.CreateEntry($p.Name, [System.IO.Compression.CompressionLevel]::Optimal)
        $es = $entry.Open()
        try { $es.Write($bytes, 0, $bytes.Length) } finally { $es.Dispose() }
      }
    } finally { $zip.Dispose() }
  } finally { $fs.Dispose() }
  $size = (Get-Item -LiteralPath $path).Length
  if ($bad -gt 0) { throw ('' + $bad + ' of ' + $parts.Count + ' parts differ from the build') }
  try { Set-Clipboard -Value $path; $clip = 'the file path is on the clipboard' } catch { $clip = 'the clipboard could not be set' }
  Write-Output ('ITEM app-file PASS made __APP__ in T23: bytes=' + $size + ', parts=' + $parts.Count + ' (each SHA-256 matches the build); ' + $clip)
  Write-Output 'PASS T23 app file r1: 1 of 1'
} catch {
  $code = 1
  Write-Output ('FAIL T23 app file r1: ' + (ConvertTo-Masked ([string]$_.Exception.Message) $(if ($who) { $who.Secret } else { @() })))
}
if (-not $NoPause -and $Host.Name -eq 'ConsoleHost') { $null = Read-Host 'Press Enter to close' }
exit $code
'''


def pack(pac, out):
    subprocess.run([pac, 'canvas', 'pack', '--sources', str(SRC), '--msapp', str(out)], check=True, stdout=subprocess.DEVNULL)


def main():
    pac = os.environ.get('PAC', 'pac')
    with tempfile.TemporaryDirectory() as tmp:
        app = Path(tmp) / APP
        pack(pac, app)
        z = zipfile.ZipFile(app)
        lines = ['$parts = @(']
        for info in z.infolist():
            b = z.read(info)
            text = b.decode('ascii')
            if "'" in text or '\r' in text or text.endswith('\n') or not text:
                sys.exit('FAIL %s cannot go in single-quoted lines as it is' % info.filename)
            # One single-quoted string per line, joined with LF on the gov device (the RADE bundle cannot embed a line that
            # starts with '@, so no here-strings).
            rows = ',\n'.join("    '%s'" % ln for ln in text.split('\n'))
            lines.append("  @{ Name = '%s'; Sha = '%s'; Text = (@(\n%s\n  ) -join \"`n\") }" % (info.filename, hashlib.sha256(b).hexdigest(), rows))
        lines.append(')')
    body = HEAD + '\n'.join(lines) + '\n' + TAIL.replace('__APP__', APP)
    OUT.write_text(body, newline='\n')
    print('BUILT %s parts=%d bytes=%d' % (OUT.relative_to(ROOT), len(z.infolist()), len(body)))


if __name__ == '__main__':
    main()
